// Reads backend/persona/*.md and writes src/persona.generated.ts so the Worker can bundle
// David's persona without any file-system access at runtime.
//
// - HTML comments are instructions for David and are stripped.
// - A "<!-- STATUS: placeholder -->" or "<!-- STATUS: starter -->" line marks a file that
//   David hasn't finished; the status is reported by /v1/health so the app can show it.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const personaDir = join(here, "..", "persona");
const outFile = join(here, "..", "src", "persona.generated.ts");

// Fixed order keeps the prompt byte-identical between builds (better prompt caching).
const ORDER = ["about", "voice", "opinions", "products", "sample-answers"];

const files = readdirSync(personaDir)
  .filter((f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md")
  .map((f) => f.replace(/\.md$/, ""))
  .sort((a, b) => {
    const ia = ORDER.indexOf(a);
    const ib = ORDER.indexOf(b);
    if (ia === -1 && ib === -1) return a.localeCompare(b);
    if (ia === -1) return 1;
    if (ib === -1) return -1;
    return ia - ib;
  });

const entries = files.map((name) => {
  const raw = readFileSync(join(personaDir, `${name}.md`), "utf8");
  const statusMatch = raw.match(/<!--\s*STATUS:\s*([a-z-]+)\s*-->/i);
  const status = statusMatch ? statusMatch[1].toLowerCase() : "done";
  const text = raw
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\r\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return { name, status, text };
});

const body =
  "// Generated by scripts/build-persona.mjs from backend/persona/*.md. Do not edit by hand.\n" +
  "export interface PersonaFile {\n  name: string;\n  status: string;\n  text: string;\n}\n\n" +
  `export const PERSONA_FILES: PersonaFile[] = ${JSON.stringify(entries, null, 2)};\n`;

writeFileSync(outFile, body);
const summary = entries.map((e) => `${e.name}=${e.status}`).join(", ");
console.log(`persona: wrote ${entries.length} files (${summary})`);
